/**
 * Returns a short definition and an interesting fact for a given word within a category.
 * If the word exists in the dictionary, it returns the tailored curated data.
 * Otherwise, it generates an authentic Arabic linguistic insight based on the category context.
 */
export function getWordDetail(word: string, category: Category): WordFactItem {
  const cleanWord = word.trim();

  // 1. Check if category already has customized wordFacts attached
  if (category.wordFacts && category.wordFacts[cleanWord]) {
    return category.wordFacts[cleanWord];
  }

  // 2. Check curated dictionary
  if (WORD_FACTS_DICTIONARY[cleanWord]) {
    return WORD_FACTS_DICTIONARY[cleanWord];
  }

  // 3. Fallback heuristic generation based on category context
  return {
    definition: `مفردة عربية أصيلة تندرج دلالياً ضمن «${category.title}»، وترتبط بـ ${category.description || 'مفاهيم هذا الباب'}.`,
    fact: `تتميز كلمة «${cleanWord}» في المعاجم باشتقاقها المعبر الذي يجسد فصاحة الضاد وعلاقتها الوثيقة بمجموعة ${category.title}.`
  };
}
